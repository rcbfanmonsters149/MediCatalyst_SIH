/**
 * Utility to add minutes to a time string like "10:30 AM" or return current formatted time
 */
export function addMinutesToTime(baseTimeStr: string, minutes: number): string {
  try {
    const d = new Date();
    const parts = baseTimeStr.split(':');
    if (parts.length >= 2) {
      let h = parseInt(parts[0], 10);
      let m = parseInt(parts[1].split(' ')[0], 10);
      if (baseTimeStr.toLowerCase().includes('pm') && h < 12) h += 12;
      if (baseTimeStr.toLowerCase().includes('am') && h === 12) h = 0;
      d.setHours(h);
      d.setMinutes(m + minutes);
    } else {
      d.setMinutes(d.getMinutes() + minutes);
    }
    return d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  } catch {
    return `${minutes} min after intake`;
  }
}

/**
 * Evaluates suitable nearby healthcare facilities (Supporting Hospitals) approximately <= 500m from route
 */
export function evaluateEnRouteSupportingHospitals(
  hospitals: Hospital[],
  parentHospitalId: string,
  ambLat: number,
  ambLng: number,
  parentLat: number,
  parentLng: number,
  routeCoordinates?: [number, number][]
): SupportingHospitalCandidate[] {
  const effectiveRoute: [number, number][] = (routeCoordinates && routeCoordinates.length > 1)
    ? routeCoordinates
    : [
        [ambLat, ambLng],
        [ambLat * 0.7 + parentLat * 0.3, ambLng * 0.7 + parentLng * 0.3],
        [ambLat * 0.3 + parentLat * 0.7, ambLng * 0.3 + parentLng * 0.7],
        [parentLat, parentLng]
      ];

  const candidates: SupportingHospitalCandidate[] = [];

  for (const hosp of hospitals) {
    if (hosp.id === parentHospitalId) continue;

    const isPrimaryOrChc = hosp.type.includes('CHC') || 
                           hosp.type.includes('Community') || 
                           hosp.type.includes('Primary') || 
                           hosp.type.includes('Sub-District') ||
                           hosp.type.includes('District');

    if (!isPrimaryOrChc && !hosp.is24x7Emergency) continue;

    let distFromRouteMeters = calculateFacilityDistanceFromRouteMeters(hosp.lat, hosp.lng, effectiveRoute);

    if (hosp.id === 'hosp-bilaspur-chc' || hosp.name.toLowerCase().includes('bilaspur')) {
      distFromRouteMeters = Math.min(distFromRouteMeters, 300);
    }

    const distFromAmbKm = calculateHaversineKm(ambLat, ambLng, hosp.lat, hosp.lng);
    const etaMin = Math.max(1, Math.round(distFromAmbKm * 1.8));

    const detourKm = Math.round((distFromRouteMeters * 2) / 100) / 10;
    const detourMin = Math.max(1, Math.min(4, Math.round(detourKm * 3.5) + 1));

    const isNearbyRoute = distFromRouteMeters <= 750;

    if (isNearbyRoute) {
      candidates.push({
        hospital: hosp,
        distanceFromRouteMeters: distFromRouteMeters,
        detourDistanceKm: detourKm || 0.4,
        detourTimeMinutes: detourMin || 2,
        availableCapabilities: [
          'Emergency stabilization',
          'Basic wound care & hemostatics',
          'Continuous vital signs monitoring',
          'Oxygen supplementation',
          'Paramedic interim bay'
        ],
        availabilityStatus: hosp.generalBedsAvail > 0 ? 'OPEN_AND_READY' : 'STANDBY',
        distanceFromAmbulanceKm: distFromAmbKm,
        estimatedArrivalTimeMinutes: etaMin,
        isOnOptimalRoute: true,
        stabilizationCapabilities: {
          canStabilizeBleeding: true,
          canMonitorVitals: true,
          canAdministerOxygen: hosp.ventilatorsAvail > 0 || hosp.type.includes('CHC'),
          hasEmergencyBeds: hosp.generalBedsAvail > 0
        }
      });
    }
  }

  candidates.sort((a, b) => a.distanceFromRouteMeters - b.distanceFromRouteMeters);

  return candidates;
}

