/**
 * Standard Haversine distance in kilometers
 */
export function calculateHaversineKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

/**
 * Calculates perpendicular distance in meters from a point (P) to a line segment (AB)
 */
export function pointToSegmentDistanceMeters(
  pLat: number,
  pLng: number,
  aLat: number,
  aLng: number,
  bLat: number,
  bLng: number
): number {
  const latScale = 111139; // meters per degree latitude
  const lngScale = 111139 * Math.cos((pLat * Math.PI) / 180);

  const px = pLng * lngScale;
  const py = pLat * latScale;
  const ax = aLng * lngScale;
  const ay = aLat * latScale;
  const bx = bLng * lngScale;
  const by = bLat * latScale;

  const dx = bx - ax;
  const dy = by - ay;
  const lenSq = dx * dx + dy * dy;

  if (lenSq === 0) {
    return Math.hypot(px - ax, py - ay);
  }

  const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / lenSq));
  const projX = ax + t * dx;
  const projY = ay + t * dy;

  return Math.round(Math.hypot(px - projX, py - projY));
}

/**
 * Calculates minimum distance in meters from facility to any segment along the route
 */
export function calculateFacilityDistanceFromRouteMeters(
  facilityLat: number,
  facilityLng: number,
  routeCoordinates: [number, number][]
): number {
  if (!routeCoordinates || routeCoordinates.length === 0) return 9999;
  if (routeCoordinates.length === 1) {
    const distKm = calculateHaversineKm(facilityLat, facilityLng, routeCoordinates[0][0], routeCoordinates[0][1]);
    return Math.round(distKm * 1000);
  }

  let minDistanceMeters = Infinity;
  for (let i = 0; i < routeCoordinates.length - 1; i++) {
    const [aLat, aLng] = routeCoordinates[i];
    const [bLat, bLng] = routeCoordinates[i + 1];
    const d = pointToSegmentDistanceMeters(facilityLat, facilityLng, aLat, aLng, bLat, bLng);
    if (d < minDistanceMeters) {
      minDistanceMeters = d;
    }
  }

  return minDistanceMeters;
}

